function applyLanguage(lang) {
  lang = lang || localStorage.getItem('ck_lang') || 'en';
  window._ckLang = lang;
  localStorage.setItem('ck_lang', lang);

  var dict = I18N[lang] || I18N.en;

  var kickerEl1 = document.getElementById('i18n-kicker');
  if(kickerEl1) kickerEl1.textContent = dict.kicker;
  var kickerEl2 = document.getElementById('i18n-kicker2');
  if(kickerEl2) kickerEl2.textContent = dict.kicker;

  var titleEl = document.getElementById('i18n-title');
  if(titleEl) titleEl.textContent = dict.title;
  var subEl = document.getElementById('i18n-sub');
  if(subEl) subEl.textContent = dict.sub;

  var lblName = document.getElementById('lbl-name');
  if(lblName) lblName.textContent = dict.name_label;
  var lblGender = document.getElementById('lbl-gender');
  if(lblGender) lblGender.textContent = dict.gender_label;
  var optMale = document.getElementById('opt-male');
  if(optMale) optMale.textContent = dict.male;
  var optFemale = document.getElementById('opt-female');
  if(optFemale) optFemale.textContent = dict.female;
  var optOther = document.getElementById('opt-other');
  if(optOther) optOther.textContent = dict.other;

  var lblDob = document.getElementById('lbl-dob');
  if(lblDob) lblDob.textContent = dict.dob_label;
  var lblTob = document.getElementById('lbl-tob');
  if(lblTob) lblTob.textContent = dict.tob_label;
  var lblPlace = document.getElementById('lbl-place');
  if(lblPlace) lblPlace.textContent = dict.place_label;
  var lblLat = document.getElementById('lbl-lat');
  if(lblLat) lblLat.textContent = dict.lat_label;
  var btnGen = document.getElementById('btn-generate');
  if(btnGen) btnGen.textContent = dict.cast_btn;

  var lblStyle = document.getElementById('lbl-style');
  if(lblStyle) lblStyle.textContent = dict.style_label;
  var btnSimp = document.getElementById('btn-mode-simp');
  if(btnSimp) btnSimp.textContent = dict.mode_simplified;
  var btnDet = document.getElementById('btn-mode-det');
  if(btnDet) btnDet.textContent = dict.mode_detailed;

  var tabOv = document.querySelector('#tab-btn-overview .tab-txt');
  if(tabOv) tabOv.textContent = dict.tab_overview;
  var tabCar = document.querySelector('#tab-btn-career .tab-txt');
  if(tabCar) tabCar.textContent = dict.tab_career;
  var tabLov = document.querySelector('#tab-btn-love .tab-txt');
  if(tabLov) tabLov.textContent = dict.tab_love;
  var tabHea = document.querySelector('#tab-btn-health .tab-txt');
  if(tabHea) tabHea.textContent = dict.tab_health;
  var tabWea = document.querySelector('#tab-btn-wealth .tab-txt');
  if(tabWea) tabWea.textContent = dict.tab_wealth;

  var btnBack = document.getElementById('btn-back');
  if(btnBack) btnBack.textContent = dict.cast_another;
  var btnSave = document.getElementById('btn-save');
  if(btnSave) btnSave.textContent = dict.save_db;
  var btnPdf = document.getElementById('btn-export-pdf');
  if(btnPdf) btnPdf.textContent = dict.export_pdf;

  var langSelect = document.getElementById('lang-select');
  if(langSelect) langSelect.value = lang;

  if(window._kd && typeof renderTab === 'function') {
    renderTab(window._currentTab || 'overview');
  }
}

var langSelectEl = document.getElementById('lang-select');
if(langSelectEl){
  langSelectEl.addEventListener('change', function(){
    applyLanguage(this.value);
  });
}

(function(){
  var saved = localStorage.getItem('ck_lang') || 'en';
  applyLanguage(saved);
})();

window.I18N = I18N;
window.applyLanguage = applyLanguage;
